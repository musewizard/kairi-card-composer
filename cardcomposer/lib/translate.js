// ★ 注意排除 U+30FB「・」和 U+30FC「ー」：它们落在片假名区里，但是标点/长音符，
//   中文文本里也会出现（官方中文说明里就有「封印・能量封印」），不排除会误报「这是日文」。
//   ★ 半角片假名（U+FF66..FF9F）也算日文，否则「使用ｶｰﾄﾞｺｽﾄ」会被当成没日文而漏翻。
const KANA = /[\u3041-\u3096\u30A1-\u30FA\u30FD-\u30FE\uFF66-\uFF9F]/;
// 纯汉字但只在日文里这么写的词（中文说明用的是「敌/攻击/行动/合计」这类，不会撞车）
