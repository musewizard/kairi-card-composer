// ★ 半角→全角必须用**显式表**：小写假名（ｧｨｩｪｫｬｭｮｯ）与 ﾝ/ｰ 的位置和
//   「假名序号 + 0x30A6」的简单偏移对不上，用算术会算出完全不同的字（曾把 ﾁｪｲﾝ 变成 チオゲポ）。
const HALF_TABLE = '｡｢｣､･ｦｧｨｩｪｫｬｭｮｯｰｱｲｳｴｵｶｷｸｹｺｻｼｽｾｿﾀﾁﾂﾃﾄﾅﾆﾇﾈﾉﾊﾋﾌﾍﾎﾏﾐﾑﾒﾓﾔﾕﾖﾗﾘﾙﾚﾛﾜﾝﾞﾟ';
const HALF_FULL = '。「」、・ヲァィゥェォャュョッーアイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワン゛゜';
const HALF_MAP = (() => { const m = {}; for (let i = 0; i < HALF_TABLE.length; i++) m[HALF_TABLE[i]] = HALF_FULL[i]; return m; })();
const DAKUTEN = { カ: 'ガ', キ: 'ギ', ク: 'グ', ケ: 'ゲ', コ: 'ゴ', サ: 'ザ', シ: 'ジ', ス: 'ズ', セ: 'ゼ', ソ: 'ゾ', タ: 'ダ', チ: 'ヂ', ツ: 'ヅ', テ: 'デ', ト: 'ド', ハ: 'バ', ヒ: 'ビ', フ: 'ブ', ヘ: 'ベ', ホ: 'ボ', ウ: 'ヴ' };
const HANDAKU = { ハ: 'パ', ヒ: 'ピ', フ: 'プ', ヘ: 'ペ', ホ: 'ポ' };
function normalizeKana(s) {
  let out = '';
  for (const c of String(s || '')) {
    const f = HALF_MAP[c];
    if (f === undefined) { out += c; continue; }
    if (f === '゛') { out = out.slice(0, -1) + (DAKUTEN[out.slice(-1)] || out.slice(-1)) + ''; continue; }
    if (f === '゜') { out = out.slice(0, -1) + (HANDAKU[out.slice(-1)] || out.slice(-1)) + ''; continue; }
    out += f;
  }
  return out;
}

