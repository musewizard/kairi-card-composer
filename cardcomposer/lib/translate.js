// ---- ④ 剩余助词（最小处理，够看懂就行）
const PARTICLES = [
  ['の', '的'], ['を', ''], ['と', '和'], ['に', ''], ['が', ''], ['は', ''], ['も', '也'],
  ['へ', '向'], ['で', ''], ['より', '比'], ['から', '从'], ['です', ''], ['ます', ''],
];

function toChinese(text) {
  const original = String(text || '');
  if (!looksJapanese(original)) return original;        // 本来就是中文/英文 → 一个字都不动
  let s = original;
  for (const [jp, cn] of HALF) s = s.split(jp).join(cn);
  s = normalizeKana(s);
  for (const [re, fn] of RULES) s = s.replace(re, fn);
  for (const [jp, cn] of PHRASES) if (jp && s.indexOf(jp) >= 0) s = s.split(jp).join(cn);
  for (const [jp, cn] of PARTICLES) if (jp && s.indexOf(jp) >= 0) s = s.split(jp).join(cn);
  // 助词清理后可能出现「/ ，」这类空档，收一下
  s = s.replace(/\/{2,}/g, '/').replace(/\s{2,}/g, ' ').replace(/、\s*$/, '');
  return s;
}

/** 翻完之后还剩假名吗（剩下的多是专有名词/画师名）。 */
function hasJapanese(text) { return KANA.test(String(text || '')); }

/** 界面用：还留着假名就标个「(日服原文)」，让用户知道这段没完全转。 */
function toChineseMarked(text, opts) {
  const out = toChinese(text);
  if (!hasJapanese(out)) return out;
  if (opts && opts.keepMarker === false) return out;
  return out + '（日服原文）';
}

/** 卡名：画师署名之类的专有名词保留，其余按词表转。 */
function cardName(name) {
  const out = toChinese(name);
  return out;
}

